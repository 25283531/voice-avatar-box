"""MAC 地址口径的唯一真源。

为什么单独一个模块
------------------
同一个 MAC 在这个系统里会以**两种写法**出现，且两种写法历史上都被写进了库：

    ``aa:bb:cc:dd:ee:ff``   固件 ``SystemInfo::GetMacAddress()`` 的产出，
                             也是 OTA 端点 ``Device-Id`` 请求头的原值；
    ``aabbccddeeff``        ``Device.device_id`` 的历史存量格式（网页端
                             「登记设备」表单里用户手输的就是这种）。

2026-10-20 之前这两条路各走各的：``voice.ota_check`` 拿**原值**当
``ActivationCode.device_id``，``devices.create_device`` 存**用户输入值**。
后果不是「不好看」，而是两个功能性故障：

1. ``_find_device`` 用 ``lower()`` 比较，带冒号与不带冒号永远不相等 ⇒
   一台**已经绑定**的设备会被判成未绑定，从而被下发激活码（违反「已绑定
   设备不再下发激活码」）；
2. 「同一台设备同一时刻只有一枚有效码」的锁定按 ``device_id`` 做键 ⇒
   两种写法各持一枚，锁定在这台设备上直接失效。

所以：**入库与比较一律先过 :func:`norm_mac`**，对外展示/日志想保留冒号就用
原值，但绝不拿原值当键。
"""
from __future__ import annotations

__all__ = ["mac_variants", "norm_mac"]


def norm_mac(value: str) -> str:
    """归一化 MAC：只留字母数字、转小写。

    只留字母数字（而不是只去冒号）是刻意的：``aa-bb-cc-dd-ee-ff``、
    ``AA:BB:CC:DD:EE:FF``、``aabbccddeeff`` 三种写法都会落到同一个键上。
    固件与网页表单谁多写一个分隔符，都不该长成两台设备。

    非 MAC 的垃圾输入（超长串、SQL 特殊字符）也会被「只留字母数字」过滤成
    安全字符集 —— 但**不校验长度**：本函数只负责口径统一，长度/合法性由
    调用方按场景决定（``ota_check`` 只要求非空，因为老固件可能上报别的标识）。
    """
    return "".join(ch for ch in (value or "") if ch.isalnum()).lower()


def mac_variants(value: str) -> tuple[str, ...]:
    """返回该 MAC 在库里**可能出现的全部历史写法**，用于查询与清理存量数据。

    为什么需要：归一化只对**新写入**生效。库里已经存在按别的写法建的行，
    而查询/作废若只按一种写法做，那些行就**查不到**（功能性故障）或
    **继续有效**（安全故障）。

    ⚠️ 为什么必须包含**大写**写法（这是一次真实的回归，别删）
    ------------------------------------------------------
    本函数原先只返回 ``(norm, colon_form)`` 两种**小写**形态，配合
    ``Device.device_id IN (...)`` 做查询。而它替换掉的那版查询是::

        func.lower(func.replace(func.replace(Device.device_id, ":", ""), "-", "")) == norm

    那个 ``lower()`` 是**刻意**用来容忍大小写的。换成 ``IN`` 之后，
    SQLite 的默认 BINARY 排序规则下 ``'AA:BB:CC:DD:EE:FF'`` 与两个小写
    候选值**都不相等** ⇒ 一台大写存量的已绑定设备会被判成「未绑定」，
    服务端于是给它下发激活码，直接违反「已绑定设备不再下发激活码」。
    这类行**确实可能存在**：MAC 标签普遍印成大写，而
    ``devices.create_device`` 在统一归一化之前是「用户输什么存什么」。

    所以：**用「把大小写/分隔符的各种组合都列进常量 IN 列表」来替代列上的
    ``lower()``**。这样既恢复了旧写法能命中的范围，又保住了索引 ——
    ``IN`` 的每个值都是常量，``device_id`` 上的索引照常可用；而
    ``lower(col)`` 把列包进函数，索引直接废掉（见 schema_patch.NEW_INDEXES）。

    ⚠️ 这是**双保险**，不是唯一防线：``schema_patch.normalize_device_macs()``
    会把存量收敛成 ``norm`` 一种写法（那之后本函数只剩一个元素）。但两者
    **不能互相替代** —— 迁移可能因为唯一约束冲突而拒绝执行（报错等人工），
    那时仍要靠本函数把大写行找出来。

    ⚠️ 为什么是 6 种、以及这个上界是怎么算出来的
    -------------------------------------------
        6 = {全小写, 全大写} × {无分隔, 全 ``:``, 全 ``-``}

    这**不是**「猜一些可能的值」，也**不是**「恰好等于改造前」——
    被替换掉的 ``lower(replace(replace(...)))`` 覆盖面其实**严格更大**
    （``lower()`` 是逐字符折叠，理论上覆盖 ``2^12`` 种大小写组合 × 任意插入
    位置，见下）。6 是从**写入路径的输出闭包**推出来的：

        固件 ``SystemInfo::GetMacAddress()``  -> 统一冒号、统一小写
        网页「登记设备」表单（手输）          -> 统一写法、统一大小写
                                                 （人不会敲 ``Aa:bB:``）

    ⇒ 往这里加一种写法之前，先回答：**哪条写路径能产出它？**

      * 答得出（"MAC 标签印成全大写" ⇒ 加。砍掉它就是本轮修的那个回归）；
      * 答不出（逐字符混大小写、重复 ``aa::bb``、错位分隔符）⇒ 不加，
        由 ``schema_patch.normalize_device_macs()`` 收敛。

    覆盖模型是**枚举**而不是**闭包**，这是刻意的：枚举有可复核的上界
    （能指着两条写路径说清为什么是 6），闭包没有。

    ⚠️ 所以它**不是**旧写法的等价替换，覆盖面**严格更窄**：混合大小写
    （``Aa:Bb:..``）、混合分隔符（``aa:bb-cc:..``）、重复分隔符（``aa::bb..``）
    这三族本函数都不覆盖，只能靠迁移收敛。⇒ 部署前必须跑一次存量 MAC
    检查确认迁移能成功执行，见 docs/DEPLOY.md。

    为什么不继续往上加（``_`` / ``.`` / 空格…）：同上 —— 答不出「哪条写入
    路径产出它」，且分隔符是**开放集合**，塞进 ``IN`` 列表会让它无限膨胀，
    并把「容忍多少种写法」这个职责从迁移（``norm_mac`` 能吃任意非字母数字）
    糊到查询侧。查询侧只负责覆盖两条写路径的产出，收敛存量是迁移的活。

    返回顺序把 ``norm`` 放最前（命中率最高）。
    """
    norm = norm_mac(value)
    out = [norm, norm.upper()]
    if len(norm) == 12 and all(c in "0123456789abcdef" for c in norm):
        for sep in (":", "-"):
            spaced = sep.join(norm[i:i + 2] for i in range(0, 12, 2))
            out.extend([spaced, spaced.upper()])
    return tuple(dict.fromkeys(out))
